    private static CmkLearningTopic Teach(string id, string title, string locator,
        string concept, string distinction, string example, string[] stages,
        string prompt, string[] choices, int correct)
    {
        string[] questions = [concept, distinction, example,
            "Bu kavramsal haritayı güncel resmî madde, ek/geçici hüküm ve işlem tarihiyle karşılaştırın."];
        string[] documents = ["Kavram ve kişi/işlem sıfatı", "İşlem türlerini karşılaştırma notu",
            "Kimliksiz eğitim örneği", "Mevzuat.gov.tr güncel metni: henüz doğrulanmadı"];
        var flow = stages.Select((stage, i) => new CmkLearningStep(i + 1, stage,
            questions[i], documents[i], "İNSAN KONTROLÜ — kavramsal öğrenme, işlem izni değil")).ToArray();
        var matrix = flow.Select(x => new CmkLearningTableRow(x.Stage, x.ReviewPrompt,
            x.DocumentToInspect, "Güncel norm / olay tarihi ayrıca doğrulanmalı")).ToArray();
        // A second question tests the topic-specific conceptual distinction, not the generic source warning.
        CmkLearningQuizQuestion[] quiz = [
            new(prompt, Array.AsReadOnly(choices), correct,
                concept + " " + distinction),
            new("Bu konuda hangi ayrımı öğrenmeliyiz?",
                Array.AsReadOnly(new[] { "Bütün işlem türleri aynı sonucu doğurur.",
                    "Bir dersin tamamlanması somut işlem için yeterli izin verir.", distinction }), 2,
                example + " Eğitim yanıtı somut dosyada karar veya hukukî uygunluk sonucu değildir.")
        ];
        return new CmkLearningTopic(id, "CMK sistematik öğrenme", title, locator, concept,
            Array.AsReadOnly(flow), Array.AsReadOnly(matrix), Array.AsReadOnly(quiz));
    }

